    return `<ellipse cx="${x}" cy="${y + 17}" rx="14" ry="15" fill="#aeb3b8" stroke="#333" stroke-width="2"/><path d="M${x - 9},${y + 5}Q${x - 12},${y - 9} ${x},${y - 9}Q${x + 12},${y - 9} ${x + 9},${y + 5}" ${trazo}/>`;
  if (tipo === "goblet")
    return `<rect x="${x - 9}" y="${y - 14}" width="18" height="28" rx="4" fill="#aeb3b8" stroke="#333" stroke-width="2"/>`;
  if (tipo === "balon")
    return `<circle cx="${x}" cy="${y + 7}" r="16" fill="white" stroke="#555" stroke-width="2"/><path d="M${x - 15},${y + 7}H${x + 15}M${x},${y - 8}V${y + 22}" ${trazo}/>`;
  if (tipo === "polea")
    return `<path d="M${x},${y}L235,35V254M221,254H249" ${trazo}/>`;
  if (tipo === "poleaBaja")
    return `<path d="M${x},${y}L238,237V45M220,254H249" ${trazo}/>`;
  if (tipo === "banda")
    return `<path d="M${p.w[0]},${p.w[1]}Q125,${y + 10} ${p.w[2]},${p.w[3]}" stroke="#a14b4d" stroke-width="5" fill="none"/>`;
